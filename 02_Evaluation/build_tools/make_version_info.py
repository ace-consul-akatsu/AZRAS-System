# -*- coding: utf-8 -*-
"""PATCH_048: write the PyInstaller Windows version resource from VERSION.json.

VERSION.json is the single source of truth for the product version.  The
version_info file PyInstaller reads must be a Python expression
(VSVersionInfo(...)); it used to be a one-line text ("AZRAS Planning v1.0.614"),
which PyInstaller cannot eval, so the EXE build stopped there.  The build
script now regenerates it from VERSION.json before every build, so the EXE's
file properties can never drift from the product version again.

Run: python build_tools/make_version_info.py            (writes the file)
     python build_tools/make_version_info.py --check    (exit 1 if stale)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPANY = "ACE Comprehensive Consulting Co., Ltd."


def _four_part(version: str, patch) -> tuple:
    parts = [int(p) for p in str(version).split(".")[:3]]
    parts += [0] * (3 - len(parts))
    return tuple(parts + [int(patch or 0)])


def render(data: dict) -> str:
    product = str(data.get("product_name") or data.get("product") or "AZRAS")
    version = str(data["version"])
    patch = int(data.get("patch") or 0)
    exe = str(data.get("executable_name") or "AZRAS")
    nums = _four_part(version, patch)
    text_ver = f"{version} (PATCH {patch:03d})"
    return f"""# -*- coding: utf-8 -*-
# GENERATED by build_tools/make_version_info.py from VERSION.json - do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={nums!r},
    prodvers={nums!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('041104B0', [
        StringStruct('CompanyName', {COMPANY!r}),
        StringStruct('FileDescription', {product!r}),
        StringStruct('FileVersion', {text_ver!r}),
        StringStruct('InternalName', {exe!r}),
        StringStruct('LegalCopyright', {'MIT License - ' + COMPANY!r}),
        StringStruct('OriginalFilename', {exe + '.exe'!r}),
        StringStruct('ProductName', {product!r}),
        StringStruct('ProductVersion', {text_ver!r})
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1041, 1200])])
  ]
)
"""


def output_path(data: dict) -> Path:
    """version_info_<executable_name>.txt - the file the product's .spec reads."""
    return ROOT / f"version_info_{data.get('executable_name') or 'AZRAS'}.txt"


def main(argv) -> int:
    data = json.loads((ROOT / "VERSION.json").read_text(encoding="utf-8-sig"))
    text = render(data)
    OUTPUT = output_path(data)
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"[NG] {OUTPUT.name} does not match VERSION.json; run build_tools/make_version_info.py")
            return 1
        print(f"[OK] {OUTPUT.name} matches VERSION.json")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\r\n")
    print(f"wrote {OUTPUT.name}: {data['version']} PATCH {int(data.get('patch') or 0):03d}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
